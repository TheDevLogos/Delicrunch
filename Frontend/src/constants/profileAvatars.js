// Obtener avatar por ID
export const getAvatarById = (id) => {
  return PROFILE_AVATARS.find(a => a.id === id) || PROFILE_AVATARS[0];
};

// Filtrar avatares por categoría
export const getAvatarsByCategory = (category) => {
  if (category === 'all') return PROFILE_AVATARS;
  return PROFILE_AVATARS.filter(a => a.category === category);
};

